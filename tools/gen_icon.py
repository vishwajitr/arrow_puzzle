#!/usr/bin/env python3
"""Generates the launcher icon (adaptive + legacy vector drawables) and store/icon-512.png from one geometry.

The icon is a tiny Arrow Escape board: a 4x4 grid fully packed with six interlocking arrows, highlighting the one that
can leave right now. Usage: python3 tools/gen_icon.py [preview.png]  (needs Pillow)
"""
import os
import sys
from PIL import Image, ImageDraw

ROOT = os.path.join(os.path.dirname(__file__), "..")
RES = os.path.join(ROOT, "app", "src", "main", "res")
# White icon, matching the game: navy ink arrows (Classic style), the free one in the brand blue, on a light-blue board.
BG, PANEL, INK, FREE = "#FFFFFF", None, "#1B2133", "#2F5BEA"  # PANEL None: no board panel (launchers crop to circles)
PANEL_BOX, PANEL_R = (20, 20, 88, 88), 12  # the "board" behind the arrows
DIRS = {"U": (0, -1), "D": (0, 1), "L": (-1, 0), "R": (1, 0)}

# Arrows as (direction, cells head-first) on a 4x4 grid (row, col); same rules as the game. Every cell is used, and it
# is a real chain: blue leaves, then the one above it, the top row, the left column, then the two bent arrows.
ARROWS = [
    ("R", [(0, 2), (0, 1), (0, 0)]),  # blocked by the short arrow on its right
    ("D", [(3, 3), (2, 3)]),          # free: nothing below it -> highlighted
    ("D", [(1, 3), (0, 3)]),          # blocked by blue
    ("U", [(1, 0), (2, 0), (3, 0)]),  # blocked by the top row
    ("L", [(1, 1), (1, 2), (2, 2)]),  # bent; blocked by the left column
    ("U", [(2, 1), (3, 1), (3, 2)]),  # bent; blocked by the arrow above
]
FREE_INDEX = 1

# 108-unit adaptive-icon viewport; everything stays inside the 66-unit safe zone (21..87).
# Everything must fit the circular mask some launchers apply: radius 33 around (54, 54).
ORIGIN, STEP = 34.5, 13        # cell centres at 34.5 .. 73.5
STROKE, TIP, BACK, HALF, STUB = 4.6, 5.2, 1.0, 4.8, 5.0  # short heads leave a gap before the next tail


def centre(rc):
    r, c = rc
    return ORIGIN + STEP * c, ORIGIN + STEP * r


def shapes():
    """Yields (colour, polyline points, triangle points) per arrow in viewport units."""
    for i, (d, cells) in enumerate(ARROWS):
        dx, dy = DIRS[d]
        pts = [centre(rc) for rc in reversed(cells)]  # tail .. head
        hx, hy = pts[-1]
        if len(pts) == 1:  # single-cell arrow: short tail so it still reads as an arrow
            pts.insert(0, (hx - dx * STUB, hy - dy * STUB))
        sx, sy = -dy, dx
        tri = [(hx + dx * TIP, hy + dy * TIP),
               (hx - dx * BACK + sx * HALF, hy - dy * BACK + sy * HALF),
               (hx - dx * BACK - sx * HALF, hy - dy * BACK - sy * HALF)]
        yield (FREE if i == FREE_INDEX else INK), pts, tri


def check_fits():
    for _, pts, tri in shapes():
        for x, y in tri + [(px, py) for px, py in pts]:
            pad = 0 if (x, y) in tri else STROKE / 2
            assert ((x - 54) ** 2 + (y - 54) ** 2) ** 0.5 + pad <= 33, f"({x}, {y}) leaves the circular safe zone"


def fmt(v):
    return f"{v:g}"


def vector(paths_xml, background=None):
    bg = f'    <path android:fillColor="{background}" android:pathData="M0,0h108v108h-108z" />\n' if background else ""
    return ('<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
            '    android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">\n'
            + bg + paths_xml + "</vector>\n")


def arrow_paths(mono=False):
    out = ""
    for colour, pts, tri in shapes():
        colour = "#FFFFFF" if mono else colour
        line = "M" + " L".join(f"{fmt(x)},{fmt(y)}" for x, y in pts)
        out += (f'    <path android:strokeColor="{colour}" android:strokeWidth="{fmt(STROKE)}" android:strokeLineCap="round"'
                f' android:strokeLineJoin="round" android:pathData="{line}" />\n')
        out += f'    <path android:fillColor="{colour}" android:pathData="M' + " L".join(f"{fmt(x)},{fmt(y)}" for x, y in tri) + ' Z" />\n'
    return out


HEADER = "<!-- Generated by tools/gen_icon.py: edit the script, not this file. -->\n"


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as f:
        f.write(HEADER + text)


x0, y0, x1, y1 = PANEL_BOX
panel = "" if PANEL is None else (f'    <path android:fillColor="{PANEL}" android:pathData="M{x0 + PANEL_R},{y0} H{x1 - PANEL_R} A{PANEL_R},{PANEL_R} 0 0 1 {x1},{y0 + PANEL_R}'
         f' V{y1 - PANEL_R} A{PANEL_R},{PANEL_R} 0 0 1 {x1 - PANEL_R},{y1} H{x0 + PANEL_R} A{PANEL_R},{PANEL_R} 0 0 1 {x0},{y1 - PANEL_R}'
         f' V{y0 + PANEL_R} A{PANEL_R},{PANEL_R} 0 0 1 {x0 + PANEL_R},{y0} Z" />\n')
check_fits()
write(os.path.join(RES, "drawable", "ic_launcher_background.xml"), vector(panel, BG))
write(os.path.join(RES, "drawable", "ic_launcher_foreground.xml"), vector(arrow_paths()))
write(os.path.join(RES, "drawable", "ic_launcher_monochrome.xml"), vector(arrow_paths(mono=True)))
write(os.path.join(RES, "mipmap", "ic_launcher.xml"), vector(panel + arrow_paths(), BG))  # API 24-25: plain square icon


def render(size, rounded=False):
    k = size * 4 / 108  # draw at 4x, then downsample for smooth edges
    big = Image.new("RGB", (size * 4, size * 4), BG)
    d = ImageDraw.Draw(big)
    if PANEL:
        d.rounded_rectangle([v * k for v in PANEL_BOX], radius=PANEL_R * k, fill=PANEL)
    w = STROKE * k
    for colour, pts, tri in shapes():
        p = [(x * k, y * k) for x, y in pts]
        d.line(p, fill=colour, width=round(w), joint="curve")
        for x, y in (p[0],):  # round tail cap
            d.ellipse((x - w / 2, y - w / 2, x + w / 2, y + w / 2), fill=colour)
        d.polygon([(x * k, y * k) for x, y in tri], fill=colour)
    img = big.resize((size, size), Image.LANCZOS)
    if rounded:  # launcher-style preview only
        mask = Image.new("L", img.size, 0)
        ImageDraw.Draw(mask).rounded_rectangle((0, 0, size, size), radius=size * 0.22, fill=255)
        out = Image.new("RGBA", img.size, (0, 0, 0, 0))
        out.paste(img, (0, 0), mask)
        return out
    return img


# Play store icon spec: 512x512, 32-bit PNG (RGBA), sRGB, up to 1 MB, full square (Play applies the rounded mask
# itself, so no pre-rounded corners or drop shadow).
from PIL import ImageCms
srgb = ImageCms.ImageCmsProfile(ImageCms.createProfile("sRGB")).tobytes()
store_icon = os.path.join(ROOT, "store", "icon-512.png")
render(512).convert("RGBA").save(store_icon, optimize=True, icc_profile=srgb)
with Image.open(store_icon) as chk:
    assert chk.size == (512, 512) and chk.mode == "RGBA" and os.path.getsize(store_icon) < 1024 * 1024
if len(sys.argv) > 1:
    canvas = Image.new("RGBA", (512 + 40 + 192 + 40 + 96, 512), "white")
    canvas.paste(render(512), (0, 0))
    canvas.alpha_composite(render(192, rounded=True), (552, 0))
    canvas.alpha_composite(render(96, rounded=True), (784, 0))
    canvas.save(sys.argv[1])
print("ok")
